#!/bin/sh
# Regenerates intent/README.md from the folders and plan headers under intent/ (ADR 0015).
# Usage: sh intent/generate-index.sh   (from the repo root). Never edit README.md by hand.
set -eu
cd "$(dirname "$0")"
out=README.md
{
  echo "# Intent index (generated)"
  echo
  echo "Generated by \`intent/generate-index.sh\`. Non-authoritative: it lists what exists; the"
  echo "files themselves, Jira and the ADRs are the record. Do not edit by hand."
  echo
  for dir in */; do
    dir=${dir%/}
    [ -d "$dir" ] || continue
    echo "## $dir"
    echo
    for f in intent.md spec.md; do
      if [ -f "$dir/$f" ]; then
        status=$(sed -n 's/^Status: //p' "$dir/$f" | head -1)
        echo "- [$f]($dir/$f): ${status:-no status line}"
      fi
    done
    if [ -d "$dir/plans" ]; then
      echo
      echo "| Plan | Summary | Status |"
      echo "|---|---|---|"
      for p in "$dir"/plans/*.md; do
        [ -f "$p" ] || continue
        key=$(basename "$p" .md)
        summary=$(sed -n "s/^# Plan: $key //p" "$p" | head -1)
        status=$(sed -n 's/^Status: //p' "$p" | head -1)
        echo "| [$key]($p) | ${summary:-?} | ${status:-?} |"
      done
    fi
    echo
  done
} > "$out"
echo "wrote intent/$out"
